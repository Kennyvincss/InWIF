import { chromium, devices } from 'playwright'
const OUT = process.argv[2]
const b = await chromium.launch()
const d = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })).newPage()
const errors = []; d.on('pageerror', (e) => errors.push(e.message))
await d.goto('http://127.0.0.1:3000/'); await d.waitForTimeout(2500)
await d.screenshot({ path: `${OUT}/r-landing-1.png` })
await d.screenshot({ path: `${OUT}/r-landing-full.png`, fullPage: true })
await d.goto('http://127.0.0.1:3000/app'); await d.waitForTimeout(1500)
await d.screenshot({ path: `${OUT}/r-welcome.png` })
await d.getByRole('button', { name: /Watch an address/ }).click()
await d.getByLabel('Address to watch').fill('0x156064f872eb6dedc953e7af21e7a7991910ef09')
await d.getByRole('button', { name: 'Add watch-only wallet' }).click()
await d.getByRole('link', { name: 'Open my wallet' }).click()
await d.locator('svg[role="img"]').first().waitFor({ timeout: 45000 }).catch(() => {})
await d.waitForTimeout(2500)
await d.screenshot({ path: `${OUT}/r-dashboard.png` })
await d.screenshot({ path: `${OUT}/r-dashboard-full.png`, fullPage: true })
console.log('errors:', errors.length, errors.slice(0, 2))
await b.close()
